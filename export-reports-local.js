#!/usr/bin/env node

/**
 * Local script to download reports from API and generate PDFs using pdfkit
 *
 * Usage:
 *   node export-reports-local.js
 *
 * Before running, set your environment variables:
 *   EXPORT_TOKEN=your_actual_token
 *   REPORT_IDS=id1,id2,id3,...
 */

const PDFDocument = require('pdfkit');
const fs = require('fs');
const path = require('path');
const https = require('https');

// Configuration
const API_URL = 'https://www.pickmypath.co.za/api/export-reports';
const EXPORT_TOKEN = process.env.EXPORT_TOKEN;
const REPORT_IDS = (process.env.REPORT_IDS || '').split(',').filter(id => id.trim());

if (!EXPORT_TOKEN) {
  console.error('❌ Error: EXPORT_TOKEN environment variable not set');
  console.error('Usage: EXPORT_TOKEN=your_token REPORT_IDS=id1,id2,id3 node export-reports-local.js');
  process.exit(1);
}

if (REPORT_IDS.length === 0) {
  console.error('❌ Error: REPORT_IDS environment variable not set');
  console.error('Usage: EXPORT_TOKEN=your_token REPORT_IDS=id1,id2,id3 node export-reports-local.js');
  process.exit(1);
}

console.log(`📥 Fetching ${REPORT_IDS.length} reports from API...`);

// Fetch reports from API
const postData = JSON.stringify({
  report_ids: REPORT_IDS.map(id => id.trim()),
  format: 'json'
});

const options = {
  hostname: 'www.pickmypath.co.za',
  port: 443,
  path: '/api/export-reports',
  method: 'POST',
  headers: {
    'x-export-token': EXPORT_TOKEN,
    'Content-Type': 'application/json',
    'Content-Length': postData.length
  }
};

const req = https.request(options, (res) => {
  let data = '';

  res.on('data', (chunk) => {
    data += chunk;
  });

  res.on('end', () => {
    if (res.statusCode !== 200) {
      console.error(`❌ API Error (${res.statusCode}):`, data);
      process.exit(1);
    }

    try {
      const response = JSON.parse(data);
      if (!response.success) {
        console.error('❌ API returned error:', response.error);
        process.exit(1);
      }

      console.log(`✅ Retrieved ${response.count} reports`);
      generatePDFs(response.reports);
    } catch (error) {
      console.error('❌ Error parsing API response:', error.message);
      process.exit(1);
    }
  });
});

req.on('error', (error) => {
  console.error('❌ Request error:', error.message);
  process.exit(1);
});

req.write(postData);
req.end();

// Generate PDFs from report data
function generatePDFs(reports) {
  const outputDir = path.join(process.cwd(), 'exported_reports');

  // Create output directory
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  console.log(`📄 Generating ${reports.length} PDFs...`);

  reports.forEach((report, index) => {
    const filename = `${report.student_name}_${report.id.slice(0, 8)}.pdf`;
    const filepath = path.join(outputDir, filename);

    const doc = new PDFDocument({ margin: 36 });
    const stream = fs.createWriteStream(filepath);

    doc.pipe(stream);

    // Header
    doc.fillColor('#0f1f3d');
    doc.fontSize(24).font('Helvetica-Bold').text(`${report.student_name}'s Career Report`, { align: 'center' });
    doc.fontSize(10).font('Helvetica').fillColor('#666').text(
      `Generated ${new Date(report.generated_at).toLocaleDateString('en-ZA')}`,
      { align: 'center' }
    );
    doc.moveDown(0.5);
    doc.strokeColor('#ddd').lineWidth(1).moveTo(36, doc.y).lineTo(doc.page.width - 36, doc.y).stroke();
    doc.moveDown(1);

    // Top Career Matches
    doc.fillColor('#0f1f3d').fontSize(16).font('Helvetica-Bold').text('Your Top Career Matches');
    doc.moveDown(0.5);

    const careers = report.top_careers?.careers || [];
    careers.slice(0, 6).forEach((career, i) => {
      doc.fillColor('#333').fontSize(12).font('Helvetica-Bold').text(`Rank ${i + 1}: ${career.title}`);

      if (career.match_pct) {
        doc.fillColor('#c9973a').fontSize(14).text(`${career.match_pct}% Match`);
      }

      if (career.summary) {
        doc.fillColor('#333').fontSize(10).font('Helvetica').text(career.summary);
      }

      if (career.salary_range?.entry) {
        doc.text(`Salary Range (Entry): ${career.salary_range.entry}`);
      }

      doc.moveDown(0.5);
    });

    // Footer
    doc.fontSize(8).fillColor('#999').text('Generated by PickMyPath — AI-powered career guidance', 36, doc.page.height - 36, { align: 'center' });

    doc.end();

    stream.on('finish', () => {
      console.log(`  ✓ ${filename}`);
      if (index === reports.length - 1) {
        console.log(`\n✅ All reports generated in: ${outputDir}`);
      }
    });

    stream.on('error', (error) => {
      console.error(`  ✗ Error writing ${filename}:`, error.message);
    });
  });
}
